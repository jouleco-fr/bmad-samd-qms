#!/usr/bin/env python3
"""
wire-workflows.py - make every QMS-relevant BMAD workflow load the QMS documents.

BMAD's _bmad/scripts/resolve_customization.py reads a workflow's settings from
{project-root}/_bmad/custom/<skill>.toml ([workflow] table) and merges them over the
skill's own customize.toml; arrays append. This script writes one such file per entry of
assets/wiring.toml, with the QMS documents as persistent_facts.

It never overwrites a file it did not write: a <skill>.toml without the managed marker is
left alone and reported, so a team's own customisation is never lost.

Usage:
  python3 wire-workflows.py --project-root /path/to/project --wiring /path/to/wiring.toml

Prints a JSON report: written, unchanged, refused (and why).
Standard library only (Python 3.11+ for tomllib).
"""

import argparse
import json
import sys
import tomllib
from pathlib import Path

MARKER = "# Managed by the bmad-samd-qms plugin (QMS wiring)."


def render(facts):
    lines = [
        MARKER + " Per-skill override read by",
        "# _bmad/scripts/resolve_customization.py; arrays append to the skill's defaults.",
        "# Regenerated by /qms-init; edit assets/wiring.toml in the plugin instead.",
        "[workflow]",
        "persistent_facts = [",
    ]
    lines += [f'  "file:{{project-root}}/{fact}",' for fact in facts]
    lines += ["]", ""]
    return "\n".join(lines)


def wire(project_root: Path, wiring: dict):
    custom_dir = project_root / "_bmad" / "custom"
    custom_dir.mkdir(parents=True, exist_ok=True)
    written, unchanged, refused = [], [], []
    for skill, entry in sorted(wiring.get("skills", {}).items()):
        target = custom_dir / f"{skill}.toml"
        text = render(entry["facts"])
        if target.exists():
            current = target.read_text(encoding="utf-8")
            if MARKER not in current:
                refused.append({"skill": skill, "file": str(target),
                                "reason": "exists and was not written by this plugin"})
                continue
            if current == text:
                unchanged.append(skill)
                continue
        target.write_text(text, encoding="utf-8")
        written.append(skill)
    return written, unchanged, refused


def main():
    parser = argparse.ArgumentParser(description="Wire the QMS into BMAD workflows")
    parser.add_argument("--project-root", required=True)
    parser.add_argument("--wiring", required=True)
    args = parser.parse_args()
    with open(args.wiring, "rb") as f:
        wiring = tomllib.load(f)
    written, unchanged, refused = wire(Path(args.project_root).resolve(), wiring)
    print(json.dumps({"status": "refused" if refused else "success", "written": written,
                      "unchanged": unchanged, "refused": refused}, indent=2))
    sys.exit(1 if refused else 0)


if __name__ == "__main__":
    main()
